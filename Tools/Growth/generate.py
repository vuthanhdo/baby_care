"""Generate BabyCare/Domain/GrowthReferenceData.swift from the official growth reference tables.

Usage: python3 Tools/Growth/generate.py <folder with the source files> [--with-who]

The WHO tables are licensed CC BY-NC-SA 3.0 IGO (non-commercial). The app ships the CDC 2000 reference only;
pass --with-who (and add GrowthStandard.who back) once WHO has granted permission for the app.

Source files (download them into one folder first):
  WHO Child Growth Standards 2006 (only with --with-who), daily LMS from WHO's anthro package
  (https://github.com/WorldHealthOrganization/anthro, data-raw/growthstandards):
    weianthro.txt  - weight-for-age, 0-1826 days
    lenanthro.txt  - length/height-for-age, 0-1826 days (column loh: L = recumbent length, H = standing height)
  CDC 2000 growth charts (https://www.cdc.gov/growthcharts/percentile_data_files.htm):
    wtageinf.csv, lenageinf.csv - weight and recumbent length, birth to 36 months
    wtage.csv, statage.csv      - weight and stature, 2 to 20 years

WHO rows are the daily table interpolated at whole months (month x 30.4375 days), which reproduces WHO's monthly
tables to their published precision. Both standards switch from length to standing height at 24 months, as their
printed charts do. Rows stop at 60 months, the end of the WHO standard.
"""
import csv
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'BabyCare' / 'Domain' / 'GrowthReferenceData.swift'
LAST_MONTH = 60


def who_daily(path):
    rows = {}
    for r in csv.DictReader(open(path), delimiter='\t'):
        rows[(int(r['sex']), int(float(r['age'])))] = (float(r['l']), float(r['m']), float(r['s']), r.get('loh', ''))
    return rows


def who_monthly(rows, sex, height):
    out = []
    for month in range(LAST_MONTH + 1):
        day = month * 30.4375
        lo, hi = math.floor(day), math.ceil(day)
        a = rows[(sex, lo)]
        b = rows.get((sex, hi), a)  # the table ends at day 1826; 60 months is day 1826.25
        t = day - lo
        if height and a[3] != b[3]:
            # 24 months falls between the last length row and the first height row: extend the height rows back.
            a, b, t = b, rows[(sex, hi + 1)], day - hi
        out.append((month, *(a[i] + (b[i] - a[i]) * t for i in range(3))))
    return out


def cdc(path, sex, start, end):
    out = []
    for r in csv.DictReader(open(path, encoding='utf-8-sig')):
        if r['Sex'].strip() != str(sex):
            continue
        month = float(r['Agemos'])
        if start <= month < end:
            out.append((month, float(r['L']), float(r['M']), float(r['S'])))
    return out


def swift_rows(name, rows):
    body = ',\n'.join(f'        .init({m:g}, {l:.4f}, {mm:.4f}, {s:.5f})' for m, l, mm, s in rows)
    return f'    static let {name}: [GrowthLMS] = [\n{body}\n    ]\n'


def main(source, with_who=False):
    source = Path(source)
    tables = {}
    if with_who:
        weight, length = who_daily(source / 'weianthro.txt'), who_daily(source / 'lenanthro.txt')
        tables.update({
            'whoWeightBoys': who_monthly(weight, 1, False),
            'whoWeightGirls': who_monthly(weight, 2, False),
            'whoHeightBoys': who_monthly(length, 1, True),
            'whoHeightGirls': who_monthly(length, 2, True),
        })
    for sex, suffix in ((1, 'Boys'), (2, 'Girls')):
        tables[f'cdcWeight{suffix}'] = cdc(source / 'wtageinf.csv', sex, 0, 24) + cdc(source / 'wtage.csv', sex, 24, LAST_MONTH + 1)
        tables[f'cdcHeight{suffix}'] = cdc(source / 'lenageinf.csv', sex, 0, 24) + cdc(source / 'statage.csv', sex, 24, LAST_MONTH + 1)
    sources = 'the WHO Child Growth Standards (2006) and the CDC 2000 growth charts' if with_who else 'the CDC 2000 growth charts'
    text = (f'// Generated by Tools/Growth/generate.py from {sources}.\n'
            '// Do not edit by hand. Ages are in months; values are kg and cm.\n\n'
            'nonisolated enum GrowthReferenceData {\n' + '\n'.join(swift_rows(k, v) for k, v in tables.items()) + '}\n')
    TARGET.write_text(text)
    print(f'Wrote {TARGET} ({sum(len(v) for v in tables.values())} rows)')


if __name__ == '__main__':
    main(sys.argv[1], with_who='--with-who' in sys.argv[2:])
